// Writes the local Supabase URL and keys into .env.local (PLAN.md § 3.3 step 5). The model key and
// the webhook secret are never written by this script: export them in your shell or add them to
// .env.local by hand (Next reads both; the shell wins).
//
// Lines this script doesn't manage are kept as they are. The file is rewritten only when a value
// changed, because `make dev` rebuilds whenever .env.local is newer than the last build.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENV_FILE = path.join(ROOT, '.env.local');
const HEADER = '# Generated by `make setup` / `make dev` (scripts/write-env.mjs) from `supabase status`.';

function status() {
  const bin = path.join(ROOT, 'node_modules', '.bin', 'supabase');
  let out;
  try {
    // stderr carries the "new version available" notice; only stdout is JSON.
    out = execFileSync(bin, ['status', '-o', 'json'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 60_000 });
  } catch {
    console.error('✖ `supabase status` failed. Is local Supabase running? Run `make setup` (or `npx --no -- supabase start`) and retry.');
    process.exit(1);
  }
  try {
    return JSON.parse(out);
  } catch {
    console.error('✖ `supabase status -o json` did not print JSON.');
    process.exit(1);
  }
}

function pick(s, ...names) {
  for (const name of names) {
    if (typeof s[name] === 'string' && s[name] !== '') return s[name];
  }
  console.error(`✖ \`supabase status\` has none of ${names.join(', ')}.`);
  process.exit(1);
}

const s = status();
// The opaque sb_publishable_/sb_secret_ keys are preferred; older CLIs only print the JWT pair.
const managed = {
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: pick(s, 'PUBLISHABLE_KEY', 'ANON_KEY'),
  SUPABASE_URL: pick(s, 'API_URL'),
  SUPABASE_SECRET_KEY: pick(s, 'SECRET_KEY', 'SERVICE_ROLE_KEY'),
  DATABASE_URL: pick(s, 'DB_URL'),
};

const previous = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, 'utf8') : '';
const nameOf = (line) => line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/)?.[1];
const kept = previous
  .split(/\r?\n/)
  .filter((line) => line !== HEADER && !Object.hasOwn(managed, nameOf(line) ?? ''))
  .join('\n')
  .trim();

const next = [HEADER, ...Object.entries(managed).map(([k, v]) => `${k}=${v}`), ...(kept ? ['', kept] : []), ''].join('\n');

if (next === previous) {
  console.log('✔ .env.local is up to date');
} else {
  writeFileSync(ENV_FILE, next, { mode: 0o600 });
  console.log(`✔ wrote .env.local (${Object.keys(managed).join(', ')})`);
}
